/* Helper: Get list of all states */
export const getStates = () => indiaLocations.map((loc) => loc.state);

/* Helper: Get districts for a given state name */
export const getDistrictsForState = (stateName) => {
  const loc = indiaLocations.find((l) => l.state === stateName);
  return loc ? loc.districts.map((d) => d.name) : [];
};

/* Helper: Get pincodes for a given state & district name */
export const getPincodesForDistrict = (stateName, districtName) => {
  const loc = indiaLocations.find((l) => l.state === stateName);
  if (!loc) return [];
  const dist = loc.districts.find((d) => d.name === districtName);
  return dist ? dist.pincodes : [];
};
